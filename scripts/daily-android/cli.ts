import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { flashcards } from '../../src/data/android-flashcards/index.ts';
import { flashcardText, flashcardSource } from '../../src/data/android-flashcards/android-flashcards-archive.ts';
import { topics } from '../../src/data/android-fundamentals/topics.ts';
import { dailySchedule } from '../../src/data/daily-android-schedule.ts';
import { validateFlashcards, resolveFlashcardLinks } from '../../src/lib/daily-android/resources.ts';
import { validateSchedule, validatePublishedEpochs } from '../../src/lib/daily-android/schedule.ts';
import { createChallengeCatalog } from './catalog.ts';
import { parseFlashcards } from './parse-flashcards.ts';

const args = process.argv.slice(2);
let sourcePath: string | undefined;
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--verify-source' && args[i + 1]) sourcePath = args[++i];
  else if (args[i] !== '--write-report') throw new Error('Usage: npm run daily:validate -- [--write-report] [--verify-source <Markdown path>]');
}
const challenges = createChallengeCatalog();
const published = JSON.parse(await readFile(new URL('./published-schedule.json', import.meta.url), 'utf8'));
const errors = [...validateFlashcards(flashcards, topics), ...validateSchedule(dailySchedule, new Set(flashcards.map(c => c.id)), new Set(challenges.map(c => c.id))), ...validatePublishedEpochs(dailySchedule, published)];
if (createHash('sha256').update(JSON.stringify(flashcardText)).digest('hex') !== flashcardSource.cardsSha256) errors.push('Imported flashcard text fingerprint changed');
if (sourcePath) {
  const source = await readFile(sourcePath);
  if (createHash('sha256').update(source).digest('hex') !== flashcardSource.sourceSha256) errors.push('Markdown source fingerprint differs from the original import');
  if (JSON.stringify(parseFlashcards(source.toString('utf8'))) !== JSON.stringify(flashcardText)) errors.push('Questions/answers differ from the supplied source');
}
if (errors.length) { console.error(errors.join('\n')); process.exitCode = 1; }
else {
  const mapped = flashcards.filter(c => c.topicId), gaps = flashcards.filter(c => !c.topicId), topicOnly = mapped.filter(c => !c.resourceUrls?.length);
  console.log(`${flashcards.length} flashcards; ${challenges.length} challenges; schedule and mappings valid.`);
  console.log(`${mapped.length} topic mappings; ${mapped.length - topicOnly.length} cards with direct library resources; ${topicOnly.length} topic-only; ${gaps.length} unmapped.`);
  if (sourcePath) console.log('All 201 original questions and answers match the source exactly.');
  if (args.includes('--write-report')) {
    await mkdir('.astro/reports', { recursive: true });
    const clean = (value: string) => value.replaceAll('|', '\\|').replaceAll('\n', ' ');
    const gapRows = [...gaps, ...topicOnly].map(c => `| ${c.id} | ${clean(c.question)} | ${c.gap ?? 'No precise direct resource; topic link only.'} |`).join('\n');
    const rows = flashcards.map(card => {
      const links = resolveFlashcardLinks(card, topics);
      return `| ${card.id} | ${card.category} | ${links.topic ? `[${links.topic.title}](${links.topic.href})` : '—'} | ${links.resources.map(r => `[${clean(r.title)}](${r.url})`).join('; ') || '—'} |`;
    }).join('\n');
    await writeFile('.astro/reports/daily-android-resource-coverage.md', `# Flashcard resource coverage\n\nGenerated by \`npm run daily:validate -- --write-report\`.\n\n${flashcards.length} curated Q&A cards; original import retained separately; ${mapped.length} real topic mappings; ${mapped.length - topicOnly.length} cards with one or two direct resources; ${topicOnly.length} topic-only; ${gaps.length} unmapped. Titles, creators, descriptions and resource types resolve from the existing library at build time. No resource metadata is copied into the flashcard source.\n\n## Gaps deliberately omitted\n\nNo unrelated links were added to satisfy a quota. Topic-only entries retain a relevant topic but omit imprecise direct resources. Unmapped entries omit Learn More entirely.\n\n| ID | Question | Reason |\n| --- | --- | --- |\n${gapRows}\n\n## Mapping inventory\n\n| ID | Source category | Fundamentals topic | Direct resources |\n| --- | --- | --- | --- |\n${rows}\n`);
  }
}
